from pathlib import Path
from typing import List, Optional

from domain.models import Decision
from domain.ports import DecisionRepository


class ADRService:
    """Engine / Use-case Orchestrator for Architecture Decision Buffer.

    Decouples UI mechanisms from storage mechanisms via repository injection.
    Depends on the DecisionRepository port — never on a concrete adapter.
    """

    def __init__(self, repository: DecisionRepository):
        if not isinstance(repository, DecisionRepository):
            raise TypeError("repository must implement the DecisionRepository port")
        self.repository = repository

    def record_decision(self, title: str, context: str, justification: str, tag: str = "general") -> Decision:
        decision = Decision(title=title, context=context, justification=justification, tag=tag)
        return self.repository.save(decision)

    def list_decisions(self) -> List[Decision]:
        return self.repository.get_all()

    def get_decision(self, record_id: str) -> Optional[Decision]:
        return self.repository.get_by_id(record_id)

    def delete_decision(self, record_id: str) -> bool:
        """Remove a decision. Returns False when the id does not exist."""
        return self.repository.delete(record_id)

    def search_by_tag(self, tag: str) -> List[Decision]:
        """Filter decisions by tag (case-insensitive exact match).

        Prefers the ORM-level filter when the adapter offers it.
        """
        find_by_tag = getattr(self.repository, "find_by_tag", None)
        if callable(find_by_tag):
            results = find_by_tag(tag)
            wanted = tag.strip().lower()
            return [d for d in results if d.tag.strip().lower() == wanted]
        tag_norm = tag.strip().lower()
        return [d for d in self.repository.get_all() if d.tag.strip().lower() == tag_norm]

    def export_to_markdown(self, output_path: Optional[str] = None) -> str:
        if output_path is None:
            from engine.settings import load_settings, resolve_export_dir

            output_path = str(resolve_export_dir(load_settings()) / "ADR_LOG.md")
        decisions = self.repository.get_all()

        md_content = "# 📜 Architecture Decision Records (ADR Log)\n\n"
        md_content += "> Automatically generated by **OS-ADB** (Architecture Decision Buffer)\n\n"
        md_content += "---\n\n"

        if not decisions:
            md_content += "*No architectural decisions recorded yet.*\n"
        else:
            for d in decisions:
                md_content += f"## [{d.id}] {d.title}\n"
                md_content += f"- **Date:** `{d.created_at}` | **Tag:** `#{d.tag}`\n\n"
                md_content += f"### 💡 Context\n{d.context}\n\n"
                md_content += f"### ⚖️ Justification & Trade-offs\n{d.justification}\n\n"
                md_content += "---\n\n"

        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return output_path

    def publish_decision(self, record_id: str) -> dict:
        """Deliver a decision through the configured connector (n8n/slack/notion)."""
        from adapters.publishers import make_publisher
        from engine.settings import load_settings

        decision = self.repository.get_by_id(record_id)
        if decision is None:
            raise ValueError(f"Decision {record_id} not found.")
        settings = load_settings()
        self._require_connector(settings)
        return make_publisher(settings).publish(decision)

    def preview_decision(self, record_id: str) -> dict:
        """Show exactly what would be sent, without touching the network."""
        from adapters.publishers import make_publisher
        from engine.settings import load_settings

        decision = self.repository.get_by_id(record_id)
        if decision is None:
            raise ValueError(f"Decision {record_id} not found.")
        settings = load_settings()
        self._require_connector(settings)
        return make_publisher(settings).preview(decision)

    def ping_publisher(self) -> dict:
        """Validate the configured connector (no decision page created for notion)."""
        from adapters.publishers import make_publisher
        from engine.settings import load_settings

        settings = load_settings()
        self._require_connector(settings)
        return make_publisher(settings).ping()

    @staticmethod
    def _require_connector(settings) -> None:
        if settings.publisher == "n8n" and not settings.webhook_enabled:
            raise ValueError(
                "n8n publishing is disabled. Run `adb config set webhook_url <url>` "
                "and `adb config set webhook_enabled true`."
            )
